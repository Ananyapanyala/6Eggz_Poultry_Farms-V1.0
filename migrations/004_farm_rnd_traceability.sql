CREATE TABLE IF NOT EXISTS business_profile (
  id BIGSERIAL PRIMARY KEY,
  legal_name TEXT NOT NULL,
  brand_name TEXT NOT NULL,
  cin TEXT NOT NULL,
  registered_office TEXT NOT NULL,
  farm_name TEXT NOT NULL,
  farm_address TEXT NOT NULL,
  survey_numbers TEXT NOT NULL,
  farm_land_extent TEXT NOT NULL,
  land_status TEXT NOT NULL,
  bird_capacity INTEGER NOT NULL,
  bird_type TEXT NOT NULL,
  housing_system TEXT NOT NULL,
  water_source TEXT NOT NULL,
  power_source TEXT NOT NULL,
  year_of_report TEXT NOT NULL,
  project_cost_paise BIGINT NOT NULL,
  term_loan_paise BIGINT NOT NULL,
  promoter_contribution_paise BIGINT NOT NULL,
  cash_credit_limit_paise BIGINT NOT NULL,
  project_status TEXT NOT NULL,
  notes TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
)