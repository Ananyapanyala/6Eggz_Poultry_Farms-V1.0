CREATE TABLE IF NOT EXISTS products (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  category TEXT NOT NULL DEFAULT 'Everyday Eggs',
  description TEXT NOT NULL DEFAULT '',
  pack_size TEXT NOT NULL DEFAULT '',
  price_paise INTEGER,
  available BOOLEAN NOT NULL DEFAULT FALSE,
  stock_quantity INTEGER NOT NULL DEFAULT 0,
  image_url TEXT NOT NULL DEFAULT '',
  research_status TEXT NOT NULL DEFAULT 'Proposed',
  nutrient_target TEXT NOT NULL DEFAULT '',
  nutrient_amount NUMERIC,
  nutrient_unit TEXT NOT NULL DEFAULT '',
  serving_basis TEXT NOT NULL DEFAULT '',
  lab_name TEXT NOT NULL DEFAULT '',
  report_date DATE,
  report_reference TEXT NOT NULL DEFAULT '',
  evidence_approved BOOLEAN NOT NULL DEFAULT FALSE,
  public_claim TEXT NOT NULL DEFAULT '',
  storage_instructions TEXT NOT NULL DEFAULT 'Keep refrigerated where appropriate and follow the packaging instructions.',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
)