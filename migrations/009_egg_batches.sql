CREATE TABLE IF NOT EXISTS egg_batches (
  id BIGSERIAL PRIMARY KEY,
  batch_code TEXT NOT NULL UNIQUE,
  product_id UUID REFERENCES products(id) ON DELETE SET NULL,
  rnd_project_id BIGINT REFERENCES rnd_projects(id) ON DELETE SET NULL,
  farm_or_house TEXT NOT NULL DEFAULT '',
  production_date DATE,
  packing_date DATE,
  best_before_date DATE,
  quantity_produced INTEGER NOT NULL DEFAULT 0,
  saleable_quantity INTEGER NOT NULL DEFAULT 0,
  rejected_quantity INTEGER NOT NULL DEFAULT 0,
  feed_batch_id BIGINT REFERENCES feed_batches(id) ON DELETE SET NULL,
  quality_inspection_status TEXT NOT NULL DEFAULT 'Pending',
  release_status TEXT NOT NULL DEFAULT 'Quarantined',
  recall_status TEXT NOT NULL DEFAULT 'Clear',
  storage_guidance TEXT NOT NULL DEFAULT 'Follow the storage instructions printed on the approved package.',
  public_summary TEXT NOT NULL DEFAULT '',
  qr_token TEXT NOT NULL UNIQUE,
  released_by TEXT NOT NULL DEFAULT '',
  released_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (quantity_produced >= 0),
  CHECK (saleable_quantity >= 0),
  CHECK (rejected_quantity >= 0),
  CHECK (saleable_quantity + rejected_quantity <= quantity_produced)
)