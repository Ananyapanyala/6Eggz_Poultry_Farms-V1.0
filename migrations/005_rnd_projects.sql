CREATE TABLE IF NOT EXISTS rnd_projects (
  id BIGSERIAL PRIMARY KEY,
  project_code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  alternate_name TEXT NOT NULL DEFAULT '',
  product_concept TEXT NOT NULL,
  research_question TEXT NOT NULL,
  candidate_nutrients JSONB NOT NULL DEFAULT '[]'::jsonb,
  scientific_rationale TEXT NOT NULL,
  evidence_references JSONB NOT NULL DEFAULT '[]'::jsonb,
  project_owner TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'Proposed',
  protocol_summary TEXT NOT NULL DEFAULT '',
  baseline_summary TEXT NOT NULL DEFAULT '',
  feed_trial_details TEXT NOT NULL DEFAULT '',
  laboratory_plan TEXT NOT NULL DEFAULT '',
  cost_notes TEXT NOT NULL DEFAULT '',
  milestones JSONB NOT NULL DEFAULT '[]'::jsonb,
  risks_and_limitations TEXT NOT NULL DEFAULT '',
  reviewer_comments TEXT NOT NULL DEFAULT '',
  final_decision TEXT NOT NULL DEFAULT '',
  commercial_release_approved BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
)